CREATE TABLE knowledge_candidate_approval (
    approval_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '不可变批准标识',
    tenant_id VARCHAR(128) NOT NULL COMMENT '可信组织标识，逐字匹配',
    owner_id VARCHAR(128) NOT NULL COMMENT '可信批准人，也是资料所有者',
    candidate_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '修正候选标识',
    revision BIGINT NOT NULL COMMENT '本次批准的不可变候选修订',
    document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '保留原共享权限的目标资料',
    base_revision BIGINT NOT NULL COMMENT '批准时原资料CAS修订',
    content_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '候选完整内容及要求摘要',
    run_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '确认的统一质量运行',
    manifest_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '批准所依据的报告清单摘要',
    review_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '事务内重验的人工评分摘要',
    preview_document_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '批准所依据的私有校验副本',
    preview_publication_json JSON NOT NULL COMMENT '校验副本精确发布元组快照',
    content_revision BIGINT NOT NULL COMMENT '原资料真实入库的目标内容版本',
    index_generation BIGINT NOT NULL COMMENT '原资料真实入库的目标索引代次',
    job_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '同事务受理的真实入库作业',
    lifecycle_command_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '原资料UPDATE命令标识',
    command_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '候选批准命令标识',
    note VARCHAR(2000) NOT NULL COMMENT '批准人明确填写的核对说明',
    approved_at DATETIME(6) NOT NULL COMMENT 'UTC批准受理时间',
    PRIMARY KEY (approval_id),
    UNIQUE KEY uq_candidate_approval_revision (candidate_id, revision),
    UNIQUE KEY uq_candidate_approval_job (job_id),
    UNIQUE KEY uq_candidate_approval_command (command_id),
    KEY ix_candidate_approval_owner (tenant_id, owner_id, candidate_id, revision),
    CONSTRAINT ck_candidate_approval_revision CHECK (revision > 0 AND base_revision >= 0 AND content_revision > 0 AND index_generation > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_bin COMMENT='候选批准与真实资料入库的不可变审计，同事务提交';
